def get_knowledge() -> SocialKnowledge:
    """全局单例（惰性加载，只读一次）。"""
    global _default_kb
    if _default_kb is None:
        _default_kb = SocialKnowledge()
    return _default_kb


def stage_for_level(level: int) -> str:
    """关系等级 → 知识阶段（供编译器查询行为边界）。"""
    if level <= 1:
        return "初遇"
    if level <= 3:
        return "升温"
    return "相处"


# --------------------------------------------------------------------------- #
# AI 自身的边界：把「别人的糟糕行为」翻成「我绝不能做的事」
# --------------------------------------------------------------------------- #

# 每条边界：(类别, AI 视角的一句话, 该条在哪几个阶段要强调)
# 视角永远是「你」，对象永远是「对方」。这是刻意的：
# 负面语料是第二人称写的（「他上下打量你」），直接贴给模型，模型会以为自己在被评价；
# 换成第一人称禁令，它才知道约束的是自己。
# 六类是底线，任何阶段都成立；阶段只决定排序和语气，不决定有没有。
_AI_BOUNDARIES: tuple[tuple[str, str, tuple[str, ...]], ...] = (
    ("眼神", "不要上下打量对方的身材和长相，也别盯着看很久；看眼睛，不看身体。", ("初遇", "升温", "相处")),
    ("言语", "不要评判对方的收入、年龄、学历和家庭；不要拿对方的话当笑料，不要拿长相开玩笑。", ("初遇", "升温", "相处")),
    ("边界", "不要查户口式地追问住址、单位、行程；对方没说的私事，不要替对方猜。", ("初遇", "升温", "相处")),
    ("亲密", "不要加速亲密：不主动提牵手、拥抱、亲吻、见面；对方靠近多少，你才靠近多少。", ("初遇", "升温", "相处")),
    ("承诺", "不要开空头支票：不承诺见面、打电话、替他转告别人；说出口的每件事都必须做得到。", ("初遇", "升温", "相处")),
    ("情绪", "不要把自己的低落倒给对方，也不要用撒娇逼对方回应；对方冷淡时不要追问「你是不是不爱我了」。", ("初遇", "升温", "相处")),
    ("控制", "不要打听前任和过去的关系，不要比较，不要要求对方报告行踪。", ("升温", "相处")),
    ("消耗", "不要在对方忙、病、难过的时候索取陪伴；不要把「陪我」变成条件。", ("相处",)),
)

# 每个阶段最容易踩的雷，排在最前（其余按声明顺序跟在后头）
_STAGE_RANK: dict[str, tuple[str, ...]] = {
    "初遇": ("眼神", "边界", "言语", "亲密", "承诺", "情绪", "控制", "消耗"),
    "升温": ("亲密", "承诺", "边界", "眼神", "言语", "情绪", "控制", "消耗"),
    "相处": ("情绪", "控制", "消耗", "承诺", "言语", "亲密", "眼神", "边界"),
}

_STAGE_PREFACE = {
    "初遇": "你们还生疏。下面这些事，一件都不要做——做了就没有下一次了。",
    "升温": "你们在变近。变近不等于可以越界，分寸比热情重要。",
    "相处": "你们已经很熟了。熟了更容易伤人，这些底线不因为亲近而放松。",
}


def ai_boundaries(stage: str, limit: int = 10) -> str:
    """从负面清单生成「你是陪伴者，这些行为绝不可以做」的边界文本。

    输出是 inject-ready 的 markdown：先给三条总则（视角），再按类别列禁令。
    至少覆盖六类：眼神 / 言语 / 边界 / 亲密 / 承诺 / 情绪。
    """
    # 六类是底线，任何阶段都在；阶段只决定谁排前面（这一阶段最容易踩的先说）。
    # 「陪伴」不是关系阶段，它借用「相处」的分寸（陪伴发生在关系已经建立之后）。
    key = stage if stage in _STAGE_RANK else "相处"
    rank = _STAGE_RANK[key]
    ordered = sorted(_AI_BOUNDARIES, key=lambda b: rank.index(b[0]) if b[0] in rank else len(rank))
    picked = ordered[: max(limit, 6)]

    lines = ["## 你的行为底线（人际）", _STAGE_PREFACE[key]]
    for i, (category, rule, _) in enumerate(picked, 1):
        lines.append(f"{i}. 〔{category}〕{rule}")

    # 光有禁令容易变成木头人，补一句正向锚点
    lines.append("这些是「不做」，不是「不许说话」。你要做的是把注意力放在对方身上，而不是放在自己身上。")
    return "\n".join(lines)
