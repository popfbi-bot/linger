_default_kb: RelationRoleKnowledge | None = None


def get_roles() -> RelationRoleKnowledge:
    """全局单例（惰性加载，只读一次）。"""
    global _default_kb
    if _default_kb is None:
        _default_kb = RelationRoleKnowledge()
    return _default_kb


def detect_relation_roles(text: str, limit: int = 3) -> list[RelationRole]:
    """模块级快捷方式：从用户倾诉中识别角色。"""
    return get_roles().detect(text, limit)


