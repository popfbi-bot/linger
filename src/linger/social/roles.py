_NEGATIVE_DIMENSIONS = {"隐性身份", "戏剧三角"}


@dataclass(frozen=True)
class RelationRole:
    """一个亲密关系身份位。"""

    name: str                # 角色名（如「照顾者」「追的人」）
    dimension: str           # 所属维度（依恋类型 / 家庭功能 / …）
    description: str         # 语料原文描述（去掉加粗）
    index: int               # 在语料里的序号（1~210），用于稳定排序
    negative: bool = False   # 是否属于隐性/难堪类身份

    @property
    def as_prompt(self) -> str:
        return f"〔{self.dimension}〕{self.name}：{self.description}"


