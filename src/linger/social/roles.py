"""关系角色图谱：亲密关系里的人格身份（src/linger/social/data/亲密陪伴关系中的人格身份全录.md）。

为什么需要它：
    现有语料回答的是「怎么做」（行为边界）和「你正在经历什么」（有毒信号），
    这份语料回答的是「你在关系里是谁」——依恋类型、家庭功能位、权力结构、
    卡普曼戏剧三角、追逃模式、内在子人格、冲突姿态、人生阶段身份、社会标签……共 210 个身份位。

    识别用户在关系里扮演的角色，AI 才知道：
        - 用户缺什么（被照顾者 → 需要被接住；追的人 → 需要被回应；受害者 → 不能跟着批判）
        - 自己该补哪个位（互补角色）
        - 关系里正在上演什么剧本（追逃锁死 / 戏剧三角轮转 → 不能推波助澜）

设计：
    - dimension = "relation_role"，与 stage / companion_negative 并列，互不污染。
    - 角色按语料里的 14 个维度（章节）分组索引。
    - 只识别、不惩罚：角色识别绝不进入 red_flag / unresolved_conflicts——
      用户「是受害者」不是错，「是拯救者」也不是错。它只作为 orchestrator 的洞察输入。
"""

