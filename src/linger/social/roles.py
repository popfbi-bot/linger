        """用户在演某角色时，AI 该补哪些位。

        返回 [{name, description}]。name 可能来自语料（真实角色）或虚拟角色
        （语料里没有的健康位，如「安全基地」「镜子」）。
        """
        names = self._COMPLEMENT_MAP.get(role_name, ())
        result: list[dict[str, str]] = []
        for n in names[:limit]:
            role = self._by_name.get(n)
            if role is not None:
                result.append({"name": role.name, "description": role.description})
            elif n in self._VIRTUAL_ROLES:
                result.append({"name": n, "description": self._VIRTUAL_ROLES[n]})
        return result

