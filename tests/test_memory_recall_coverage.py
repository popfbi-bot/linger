"""记忆提炼的准入判断：中文主语省略也要记得住。

**发现的缺陷（2026-10-22 用户旅程走查）**：

用户说「今天面试砸了，心里堵得慌」，记忆面板显示 0 条。更严重的是
「妈妈病了」「爸爸住院了」这类句子也一条都记不住。

根因是准入条件只有「含『我』字」或「含地名/机构」两条。但中文主语省略是常态——
用户越自然，越不带代词，AI 就越健忘。这对陪伴产品是硬伤。

讽刺的是 `_HIGH_IMPORTANCE`（妈/爸/病/手术）与 `_EVENT`（面试/复查/加班）
本来就在用，只是**只用于「重要性加权」，没用于「要不要记」**，两套词表脱节。

修法：
1. 准入通道加到四条：第一人称 / 地名机构 / 高重要性词 / 具体事件词
2. 长度改成两档：4 字以下一律丢；4~5 字只放行高重要性句子
   （「妈妈病了」只有 4 个字，却是整段对话里最该记住的一句）
3. **刻意不纳入纯情绪词**（累/烦/难过）——无主语又无信息量的「最近很累」
   记下来只稀释记忆面板，它更适合留在 turn 历史里
"""

from __future__ import annotations

import pytest
from _fakes import FakeEmbedder

from linger.memory.extractor import extract_from_turns
from linger.models import Turn


def _extract(text: str):
    return extract_from_turns(
        "p_test", "u_test", [Turn(id=1, session_id="s", role="user", content=text)], FakeEmbedder()
    )


# --------------------------------------------------------------------------- #
# 1. 中文省略主语 —— 本次修复的核心
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize(
    "text",
    [
        "今天面试砸了，心里堵得慌。",   # 无「我」，含事件词「面试」
        "妈妈病了。",                   # 4 字短句，家人 + 健康
        "爸爸住院了。",                 # 5 字短句
        "下周要做手术了。",              # 无「我」，含「手术」
        "这份工作干不下去了。",          # 无「我」，含「工作」
        "工作特别累。",                 # 含「工作」→ 有领域信息量，记
    ],
)
def test_omitted_subject_still_remembered(text):
    """不带「我」但显然在说自己——必须记得住。"""
    assert _extract(text), f"漏记了：「{text}」"


# --------------------------------------------------------------------------- #
# 2. 不该记的（防止修完变成记忆垃圾桶）
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize(
    "text",
    [
        "最近很累。",       # 无主语、无领域词、无信息量
        "今天天气真好。",   # 与用户无关的闲聊
        "嗯嗯好的。",       # 碎片
        "哈哈哈。",
    ],
)
def test_should_not_be_remembered(text):
    """既没有主语、也没有领域信息量的句子不该进长期记忆。

    刻意排除「最近很累」这类：它既没说清具体什么事，也没有可召回的实体，
    记下来只会让记忆面板变成垃圾桶。它留在 turn 历史里就够了。
    而「工作特别累」不同——「工作」给了它领域信息量，所以记。
    """
    assert not _extract(text), f"不该记却记了：「{text}」"


# --------------------------------------------------------------------------- #
# 3. 回归：原本能记的还得能记
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize(
    "text",
    [
        "我妈妈下周要去医院复查。",
        "我最近压力很大。",
        "我答应了周末陪她。",
        "我很喜欢下雨天。",
    ],
)
def test_first_person_still_works(text):
    assert _extract(text)


# --------------------------------------------------------------------------- #
# 4. 长度两档的边界
# --------------------------------------------------------------------------- #
def test_four_char_high_stakes_is_kept():
    """4 字 + 高重要性 → 放行（否则「妈妈病了」这种最该记的反而丢掉）。"""
    assert _extract("妈妈病了。")


def test_four_char_without_high_stakes_is_dropped():
    """4 字但无高重要性 → 当碎片丢掉。"""
    assert not _extract("今天好累。")


def test_too_long_is_dropped():
    """超 120 字不是「记忆条目」，是长文。"""
    assert not _extract("我" + "很长的句子" * 40)


# --------------------------------------------------------------------------- #
# 5. 记忆类型仍然分得清
# --------------------------------------------------------------------------- #
def test_high_stakes_classified_as_fact_or_event():
    """准入放宽了，但分类逻辑不能乱。"""
    out = _extract("妈妈下周要去医院复查。")
    assert out
    assert out[0].layer in (2, 3)
    assert out[0].type in ("event", "fact")
    assert out[0].source_type == "user_said"